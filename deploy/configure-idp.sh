#!/usr/bin/env bash
# Interactive install-time IDP configurator. Prompts for the fields in
# deploy/idp-examples/SCHEMA.md, writes a non-secret idp.yml, and pushes the
# client_secret straight to Vault — it is never written to disk in
# plaintext, not even transiently (read via `read -s`, piped directly to
# `vault kv put` over stdin).
#
# Usage: deploy/configure-idp.sh <env> [output-path]
#   deploy/configure-idp.sh dev
#   deploy/configure-idp.sh prod /tmp/idp.entra-prod.yml
#
# Requires: `vault` CLI authenticated (VAULT_ADDR/VAULT_TOKEN, or run
# `vault login` first) with write access to
# secret/mcphub/<env>/idp/<name>.

set -euo pipefail

ENV_NAME="${1:?usage: configure-idp.sh <env> [output-path]}"
OUT_PATH="${2:-$(dirname "$0")/idp-examples/idp.${ENV_NAME}.generated.yml}"

command -v vault >/dev/null 2>&1 || { echo "vault CLI not found on PATH" >&2; exit 1; }

echo "== mcphub IDP configuration (env: ${ENV_NAME}) =="
echo

read -rp "IDP name (used as podman secret suffix, e.g. mcp-keycloak): " IDP_NAME
read -rp "OIDC issuer URL (e.g. https://keycloak.internal/realms/mcp): " ISSUER
read -rp "Client ID: " CLIENT_ID
read -rsp "Client secret (input hidden, never echoed or written to disk): " CLIENT_SECRET
echo
read -rp "Does this IDP support RFC 8693 token exchange? [y/N]: " TOKEN_EXCHANGE_ANSWER
read -rp "Default auth_mode [shared_passthrough/shared_exchange/dedicated_port]: " AUTH_MODE

case "${TOKEN_EXCHANGE_ANSWER,,}" in
  y|yes) SUPPORTS_EXCHANGE=true ;;
  *) SUPPORTS_EXCHANGE=false ;;
esac

case "$AUTH_MODE" in
  shared_passthrough|shared_exchange|dedicated_port) ;;
  *) echo "invalid auth_mode: $AUTH_MODE" >&2; exit 1 ;;
esac

if [ "$SUPPORTS_EXCHANGE" = "false" ] && [ "$AUTH_MODE" = "shared_exchange" ]; then
  echo "shared_exchange requires token-exchange support — pick dedicated_port or shared_passthrough instead, or answer yes above." >&2
  exit 1
fi

VAULT_PATH="secret/mcphub/${ENV_NAME}/idp/${IDP_NAME}"
echo
echo "Writing client_secret to Vault at ${VAULT_PATH} (value never touches disk)..."
vault kv put "$VAULT_PATH" client_secret="$CLIENT_SECRET" >/dev/null
unset CLIENT_SECRET
echo "  done."

mkdir -p "$(dirname "$OUT_PATH")"
cat > "$OUT_PATH" <<YAML
---
# Generated by deploy/configure-idp.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ) for env=${ENV_NAME}.
# client_secret is in Vault at ${VAULT_PATH} — NOT in this file.
idps:
  - name: ${IDP_NAME}
    issuer: "${ISSUER}"
    client_id: "${CLIENT_ID}"
    supports_token_exchange: ${SUPPORTS_EXCHANGE}
    default_auth_mode: ${AUTH_MODE}
YAML

echo
echo "Wrote ${OUT_PATH}"
echo "Apply it with:"
echo "  cd deploy/ansible && ansible-playbook -i inventories/${ENV_NAME}/hosts.yml playbooks/configure-idp.yml -e mcphub_idp_config_file=${OUT_PATH}"
